#!/usr/bin/env node
/**
 * Generates plugins/index.ts by scanning plugins/ for any directory that
 * contains an index.ts.
 *
 * Each plugin gets a namespace import plus a `registerPluginModule()` call
 *: a migrated plugin default-exports its definePlugin() manifest,
 * which registerPluginModule registers; a not-yet-migrated plugin has no
 * default export and still registers through its import-time `register*()`
 * side effects — any mix works, so the core and commercial repos can migrate
 * independently. `_markPluginsReady()` runs last. The core repo never names a
 * plugin — whatever directories are present on disk get loaded; missing ones
 * are silently skipped.
 *
 * Wired into package.json as predev / prebuild / pretest / preci so the
 * generated file is always up-to-date before the bundler runs.
 *
 * The generated file is gitignored in both the core and commercial repos.
 */

import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const repoRoot = resolve(__dirname, "..");
const pluginsDir = join(repoRoot, "plugins");
const outFile = join(pluginsDir, "index.ts");

const lines = [
  "// AUTO-GENERATED by scripts/generate-plugin-index.mjs. Do not edit.",
  "// Run `npm run plugins:gen` to regenerate.",
  "",
  'import { registerPluginModule } from "@/lib/plugin-manifest";',
  "",
];

const registrations = [];
const entries = readdirSync(pluginsDir).sort();
for (const name of entries) {
  if (name.startsWith("_") || name.startsWith(".")) continue;
  const dir = join(pluginsDir, name);
  let stat;
  try {
    stat = statSync(dir);
  } catch {
    continue;
  }
  if (!stat.isDirectory()) continue;
  if (!existsSync(join(dir, "index.ts"))) continue;
  const ident = `plugin_${name.replaceAll("-", "_")}`;
  lines.push(`import * as ${ident} from "./${name}";`);
  registrations.push(`registerPluginModule(${ident});`);
}

lines.push("");
lines.push(...registrations);
lines.push("");
lines.push('import { _markPluginsReady } from "./_ready";');
lines.push("_markPluginsReady();");
lines.push("");

writeFileSync(outFile, lines.join("\n"));
